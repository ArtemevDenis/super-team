import { describe, expect, it } from 'vitest';

import { addDays, daysBetween, formatDayRu, isWithin } from './dates.js';

describe('арифметика календарных дней', () => {
  it('не сбивается на переходе летнего времени', () => {
    // 9 марта 2025 — переход в США: сутки длятся 23 часа. Расчёт через
    // миллисекунды дал бы здесь 1.958 и после округления мог бы дать 1.
    expect(daysBetween('2025-03-08', '2025-03-10')).toBe(2);
    // 26 октября 2025 — переход в Европе: сутки длятся 25 часов.
    expect(daysBetween('2025-10-25', '2025-10-27')).toBe(2);
    expect(addDays('2025-03-08', 2)).toBe('2025-03-10');
  });

  it('считает через границы месяца, года и високосный февраль', () => {
    expect(daysBetween('2024-02-28', '2024-03-01')).toBe(2);
    expect(daysBetween('2025-02-28', '2025-03-01')).toBe(1);
    expect(daysBetween('2024-12-31', '2025-01-01')).toBe(1);
    expect(addDays('2024-02-28', 1)).toBe('2024-02-29');
    expect(addDays('2025-01-31', -31)).toBe('2024-12-31');
  });

  it('даёт отрицательную разницу для дат в прошлом', () => {
    expect(daysBetween('2025-05-10', '2025-05-01')).toBe(-9);
  });

  it('считает границы интервала включительно', () => {
    expect(isWithin('2025-06-01', '2025-06-01', '2025-06-10')).toBe(true);
    expect(isWithin('2025-06-10', '2025-06-01', '2025-06-10')).toBe(true);
    expect(isWithin('2025-05-31', '2025-06-01', '2025-06-10')).toBe(false);
  });

  it('форматирует дату по-русски', () => {
    expect(formatDayRu('2019-03-07')).toBe('7 марта 2019');
  });
});
